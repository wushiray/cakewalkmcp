// --- notes ------------------------------------------------------------------

export const getClips = (index) => toolCall(`
local tr = proj.tracks:GetAt(${index | 0})
if not tr or not tr.isValid then error('track ${index} not found') end
local clips = {}
for c = 1, tr.clips.count do
  local cl = tr.clips:GetAt(c)
  if cl and cl.isValid then
    clips[#clips+1] = { clipId = cl.clipId, name = cl.name or '', start = tostring(cl.start or '0'), length = tostring(cl.length or '0') }
  end
end
out.clips = clips
emit(out)
`);

export const getNotes = (index, clipIndex = 1) => toolCall(`
local tr = proj.tracks:GetAt(${index | 0})
if not tr or not tr.isValid then error('track ${index} not found') end
local clip = tr.clips:GetAt(${clipIndex | 0})
if not clip or not clip.isValid then error('clip ${clipIndex} not found') end
local events = clip:GetMIDIEventsAdv()
local notes = {}
for _, ev in ipairs(events) do
  if ev.event.type == EMIDIEventType.Note then
    notes[#notes+1] = {
      time = ev.time, pitch = ev.event.p1, velocity = ev.event.p2, duration = ev.event.dur,
      channel = ev.event.channel or 0,
    }
  end
end
out.clip = { name = clip.name or '', noteCount = #notes }
out.notes = notes
emit(out)
`);

// --- transport --------------------------------------------------------------

export const transport = (cmd) => toolCall(`
local ok, err = pcall(function()
  if ${JSON.stringify(cmd)} == 'play' then proj:Play()
  elseif ${JSON.stringify(cmd)} == 'stop' then proj:Stop()
  elseif ${JSON.stringify(cmd)} == 'record' then proj:Record()
  elseif ${JSON.stringify(cmd)} == 'pause' then proj:Pause()
  else error('unknown transport: ' .. ${JSON.stringify(cmd)}) end
end)
out.cmd = ${JSON.stringify(cmd)}
out.ok = ok
out.err = err and tostring(err) or nil
emit(out)
`);

export const locate = (time) => toolCall(`
proj:SetNowTime(${JSON.stringify(String(time))}, ETimeFormat.EBarsBeats)
out.now = tostring(proj:GetNowTime(ETimeFormat.EMusical))
emit(out)
`);

// --- utility ----------------------------------------------------------------

export function emit(s) { return toolCall(`out.note=${JSON.stringify(String(s))}\nemit(out)`); }

