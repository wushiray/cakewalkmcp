// lib/cake_templates.js — parameterised CakeScript (Lua) program templates that
// get wrapped and shipped to the SONAR AI Assistant as a write_cakescript +
// run_cakescript tool call. The helper `wrap` returns the JSON payload object
// directly consumable by the LLM_TOOL_CALL IPC.

const HDR = `-- generated by cakewalk-mcp; do not edit
local proj = cakeapp.projects:GetActiveProject()
if not proj then error('no active project') end
local out = { ok=true }
local function emit(t) print('CWOUT:' .. (type(t)=='string' and t or cakeapp.fileSystem:SerializeToJson(t))) end
`;

function wrap(body) {
  return HDR + '\n' + body + '\n';
}

function toolCall(code) {
  // Matches the AI Assistant's write_cakescript tool shape: { code }
  return { tool: 'write_cakescript', args: { code: wrap(code) } };
}

// --- queries ----------------------------------------------------------------

export const status = toolCall(`
out.appName = 'Cakewalk Sonar'
out.appPid = (require or nil)  -- placeholder; we return from host probe
out.scriptsFolder = (function() local ok, r = pcall(function() return cakeapp.cakeScriptVersion end); return ok and r or nil end)
out.project = { name = proj.name, path = proj.path or '', tracks = proj.tracks.count }
emit(out)
`);

export const listTracks = toolCall(`
local t = {}
for i = 1, proj.tracks.count do
  local tr = proj.tracks:GetAt(i)
  if tr and tr.isValid then
    t[#t+1] = {
      index = i,
      trackId = tr.trackId,
      name = tr.name or '',
      type = (function()
        local v = tr.trackType
        if v == ETrackType.EMidi then return 'midi'
        elseif v == ETrackType.EAudio then return 'audio'
        else return tostring(v) end
      end)(),
      volume = tr.volume,
      pan = tr.pan,
      mute = tr.mute,
      solo = tr.solo,
      arm = tr.arm,
      clipCount = (tr.clips and tr.clips.count) or 0,
    }
  end
end
out.tracks = t
emit(out)
`);

export const getTrack = (index) => toolCall(`
local tr = proj.tracks:GetAt(${index | 0})
if not tr or not tr.isValid then error('track ${index} not found') end
out.track = {
  index = ${index | 0},
  trackId = tr.trackId, name = tr.name, type = tostring(tr.trackType),
  volume = tr.volume, pan = tr.pan, mute = tr.mute, solo = tr.solo, arm = tr.arm,
  sendCount = (tr.sends and tr.sends.count) or 0,
  clipCount = (tr.clips and tr.clips.count) or 0,
}
emit(out)
`);

